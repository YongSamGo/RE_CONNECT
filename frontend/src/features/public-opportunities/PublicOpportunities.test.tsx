import { act, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { PublicOpportunities } from './PublicOpportunities'
import { sampleList, sampleOpportunity } from './test-fixtures'

const json = (value: unknown, status = 200) => new Response(JSON.stringify(value), { status, headers: { 'Content-Type': 'application/json' } })
function mount() { return render(<MemoryRouter><PublicOpportunities /></MemoryRouter>) }
async function search() { await userEvent.click(screen.getByRole('button', { name: '공고 검색하기' })) }
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals() })

describe('public search without AI or login', () => {
  it('waits for an explicit search and makes only a public GET request', async () => {
    const fetch = vi.fn(async (_request: Request) => json(sampleList({ items: [], total: 0 })))
    vi.stubGlobal('fetch', fetch)
    mount()
    expect(fetch).not.toHaveBeenCalled()
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
    await search()
    expect(await screen.findByText('이 조건의 공고가 없어요')).toBeVisible()
    const request = fetch.mock.calls[0]![0]
    expect(request.method).toBe('GET')
    expect(request.url).toBe('https://reconnect.test/api/v1/opportunities?page=1&page_size=20')
    expect(fetch).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('region', { name: '공고 조회 결과' })).toHaveFocus()
  })
  it('sends only the explicit trimmed filters and keeps search out of address history and storage', async () => {
    const fetch = vi.fn(async (_request: Request) => json(sampleList()))
    vi.stubGlobal('fetch', fetch)
    const write = vi.spyOn(Storage.prototype, 'setItem')
    const user = userEvent.setup()
    mount()
    await user.type(screen.getByRole('searchbox'), '  도서&role=operator  ')
    await user.selectOptions(screen.getByRole('combobox', { name: '활동 지역' }), 'seoul')
    await user.selectOptions(screen.getByRole('combobox', { name: '활동 유형' }), 'volunteering')
    await search()
    await screen.findByText('공개 공고 검색 결과')
    const query = new URL(fetch.mock.calls[0]![0].url).searchParams
    expect(Object.fromEntries(query)).toEqual({ page: '1', page_size: '20', q: '도서&role=operator', province: 'seoul', activity_type: 'volunteering' })
    expect(window.location.search).toBe('')
    expect(write).not.toHaveBeenCalled()
  })
  it('renders unknown recruitment/pay, review changes and date-only uncertainty explicitly', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => json(sampleList({ items: [sampleOpportunity({ recruitment_status: 'unknown', change_pending: true })] }))))
    mount()
    await search()
    expect(await screen.findByText('모집 여부 확인 필요')).toBeVisible()
    expect(screen.getByText('변경 내용 검수 중')).toBeVisible()
    expect(screen.getByText('보수 확인 필요')).toBeVisible()
    expect(screen.getByText('2026-10-30 마감 · 정확한 마감 시각 확인 필요')).toBeVisible()
    expect(screen.getByText(/맞춤 추천이나 자격 판정 결과가 아닙니다/)).toBeVisible()
  })
  it('renders hostile titles as text and creates only a validated internal detail link', async () => {
    const attack = '<img src=x onerror=alert(1)>'
    vi.stubGlobal('fetch', vi.fn(async () => json(sampleList({ items: [sampleOpportunity({ title: attack })] }))))
    const { container } = mount()
    await search()
    expect(await screen.findByRole('heading', { name: attack })).toBeVisible()
    expect(container.querySelector('img, script')).toBeNull()
    expect(screen.getByRole('link', { name: `${attack} 공고 상세 화면으로` })).toHaveAttribute('href', '/opportunities/12345678-1234-1234-1234-123456789001')
    expect(screen.getByText(/상세에서 최신 모집 상태와 원문 조건/)).toBeVisible()
  })
  it('uses the applied filter snapshot for pagination while leaving edited filters unapplied', async () => {
    const fetch = vi.fn(async (request: Request) => {
      const page = Number(new URL(request.url).searchParams.get('page'))
      return json(sampleList({ page, total: 21 }))
    })
    vi.stubGlobal('fetch', fetch)
    const user = userEvent.setup()
    mount()
    await user.type(screen.getByRole('searchbox'), '도서')
    await search()
    await screen.findByText('공개 공고 검색 결과')
    await user.clear(screen.getByRole('searchbox'))
    await user.type(screen.getByRole('searchbox'), '아직 적용하지 않은 조건')
    await user.click(screen.getByRole('button', { name: '다음 페이지' }))
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('2페이지'))
    expect(new URL(fetch.mock.calls[1]![0].url).searchParams.get('q')).toBe('도서')
    expect(screen.getByRole('button', { name: '다음 페이지' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: '공고 검색하기' }))
    await waitFor(() => expect(fetch).toHaveBeenCalledTimes(3))
    expect(new URL(fetch.mock.calls[2]![0].url).searchParams.get('page')).toBe('1')
  })
  it('distinguishes a zero-result query from an empty page with a nonzero total', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => json(sampleList({ items: [], total: 21 }))))
    mount()
    await search()
    expect(await screen.findByText('이 페이지에 표시할 공고가 없어요')).toBeVisible()
    expect(screen.queryByText('이 조건의 공고가 없어요')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '첫 페이지 다시 조회' })).toBeVisible()
  })
  it('keeps filters after failure, displays no internal message and retries only when asked', async () => {
    const fetch = vi.fn(async (_request: Request) => json({ code: 'SERVICE_UNAVAILABLE', message: 'private-query-and-SQL', request_id: 'req_test' }, 503))
    vi.stubGlobal('fetch', fetch)
    mount()
    await userEvent.type(screen.getByRole('searchbox'), '시설관리')
    await search()
    expect(await screen.findByRole('alert')).toHaveTextContent('서비스 연결이 원활하지 않습니다.')
    expect(screen.queryByText('private-query-and-SQL')).not.toBeInTheDocument()
    expect(screen.getByRole('searchbox')).toHaveValue('시설관리')
    expect(fetch).toHaveBeenCalledTimes(1)
    await userEvent.click(screen.getByRole('button', { name: '같은 조건으로 다시 조회' }))
    await waitFor(() => expect(fetch).toHaveBeenCalledTimes(2))
  })
  it('does not offer immediate retry for an exhausted daily quota', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => json({ code: 'DAILY_QUOTA_EXCEEDED', message: 'private', request_id: 'req_test' }, 429)))
    mount()
    await search()
    expect(await screen.findByRole('alert')).toHaveTextContent('다음 날 다시 이용해 주세요.')
    expect(screen.queryByRole('button', { name: '같은 조건으로 다시 조회' })).not.toBeInTheDocument()
  })
  it('blocks duplicate submits, cancels the request and cannot apply its result to a new search', async () => {
    let finishOld!: (response: Response) => void
    const oldResponse = new Promise<Response>((resolve) => { finishOld = resolve })
    const fetch = vi.fn(async (_request: Request) => oldResponse)
      .mockImplementationOnce(async () => oldResponse)
      .mockImplementationOnce(async () => json(sampleList({ items: [sampleOpportunity({ title: '새 검색 결과' })] })))
    vi.stubGlobal('fetch', fetch)
    mount()
    await search()
    expect(screen.getByRole('button', { name: '공고를 불러오고 있어요' })).toBeDisabled()
    await userEvent.click(screen.getByRole('button', { name: '공고를 불러오고 있어요' }))
    expect(fetch).toHaveBeenCalledTimes(1)
    await userEvent.click(screen.getByRole('button', { name: '조회 취소하기' }))
    expect(fetch.mock.calls[0]![0].signal.aborted).toBe(true)
    await search()
    expect(await screen.findByRole('heading', { name: '새 검색 결과' })).toBeVisible()
    await act(async () => { finishOld(json(sampleList({ items: [sampleOpportunity({ title: '이전 검색 결과' })] }))); await oldResponse })
    expect(screen.queryByRole('heading', { name: '이전 검색 결과' })).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: '새 검색 결과' })).toBeVisible()
  })
  it('aborts an active request when leaving the public view', async () => {
    let finish!: (response: Response) => void
    const response = new Promise<Response>((resolve) => { finish = resolve })
    const fetch = vi.fn(async (_request: Request) => response)
    vi.stubGlobal('fetch', fetch)
    const view = mount()
    await search()
    view.unmount()
    expect(fetch.mock.calls[0]![0].signal.aborted).toBe(true)
    await act(async () => { finish(json(sampleList())); await response })
  })
  it('clears public search input and cancels work across pagehide and persisted restore', async () => {
    let finish!: (response: Response) => void
    const response = new Promise<Response>((resolve) => { finish = resolve })
    const fetch = vi.fn(async (_request: Request) => response)
    vi.stubGlobal('fetch', fetch)
    mount()
    await userEvent.type(screen.getByRole('searchbox'), '복귀 전 검색어')
    await search()
    act(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: true })))
    act(() => window.dispatchEvent(new PageTransitionEvent('pageshow', { persisted: true })))
    expect(screen.getByRole('searchbox')).toHaveValue('')
    expect(fetch.mock.calls[0]![0].signal.aborted).toBe(true)
    await act(async () => { finish(json(sampleList())); await response })
    expect(screen.getByText('검색 조건을 고르고 공고를 불러오세요')).toBeVisible()
  })
  it('rejects a malformed response without rendering unsafe links or mixing it with valid cards', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => json(sampleList({ items: [sampleOpportunity({ id: '../admin' })] }))))
    mount()
    await search()
    expect(await screen.findByRole('alert')).toHaveTextContent('응답을 확인하지 못했습니다.')
    expect(screen.queryByRole('heading', { name: '가상 도서 정리 봉사' })).not.toBeInTheDocument()
    expect(screen.queryByRole('link', { name: /공고 상세 화면으로/ })).not.toBeInTheDocument()
  })
})
