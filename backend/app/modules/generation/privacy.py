"""전송 전 보수적인 표본 필터. 의미 기반 개인정보/인젝션 탐지기가 아니다.

단어 하나만으로 막으면 "안전진단", "자녀 교육 상담", "연락처 관리 업무" 같은 경력 문장까지
거절된다. 그래서 번호·건강·가족은 "알려 주는 표현"이나 "본인 사정을 말하는 표현"과 함께
나올 때만 막는다. 기대 동작과 한계는 eval/privacy_filter_cases.json과 docs/ai/privacy-filter.md.
"""

import re
import unicodedata

from pydantic import TypeAdapter, ValidationError

from app.contracts.fields import text

_TEXT = TypeAdapter(text(4000, multiline=True))
_DIGIT = "공영일이삼사오육칠팔구"
# 번호로 볼 근거는 숫자 여러 개다. 한글 숫자 한 글자("휴대폰 사용법", "전화 일")는 흔한 글자라 보지 않는다.
_TELL = (r"\s*(?:은|는|이|가|요|:|을|를)?\s*(?:알려|드릴|드려|불러|남길|적어|[0-9]{2,}|"
         r"[" + _DIGIT + r"](?:[\s\-]*[" + _DIGIT + r"]){2,})")
_ILLNESS = r"관절염|당뇨|고혈압|치매|디스크|우울증|뇌졸중|중풍|협심증|암(?![기호송살벽석])"
# 가족 호칭은 조사·띄어쓰기로 끝날 때만 본다. "딸기", "어머니회"는 가족 호칭이 아니다.
_FAMILY = (r"(?:남편|아내|배우자|자녀|아들|딸|며느리|사위|손주|손자|손녀|부모님|어머니|아버지)"
           r"(?=[^가-힣]|$|(?:이|가|은|는|께서|도|을|를|와|과|하고|랑|이랑|의|네|한테|에게|만|들))")
_FAMILY_EVENT = (r"돌아가|사망|세상을\s*떠|이혼|별거|재혼|아프|아파(?!트)|입원|간병|빚|실직|같이\s*살|함께\s*살|모시고|"
                 r"장애(?!\s*(?:아동|아이|학생|어르신|복지|시설|기관|센터))|" + _ILLNESS)
_PATTERNS = (
    # 형식이 정해진 번호·이메일
    r"(?<!\d)\d{6}\s*[- ]?\s*[1-8]\d{6}(?!\d)",
    r"(?<!\d)0\d{1,2}[- .]?\d{3,4}[- .]?\d{4}(?!\d)",
    r"[\w.+-]+@[\w.-]+\.[a-zA-Z]{2,}",
    # 한글로 불러 주는 번호: 한글 숫자 7개 이상이 공백·하이픈만 사이에 두고 이어진다
    rf"[{_DIGIT}](?:[\s\-]*[{_DIGIT}]){{6,}}",
    # 번호를 알려 주는 표현. "주민번호 확인 업무", "전화 상담", "연락처 관리"는 통과한다
    r"(?:주민\s*(?:등록)?|여권|계좌)\s*번호(?!\s*(?:확인|조회|발급|업무|관리|안내))",
    rf"전화\s*번호{_TELL}",
    rf"(?:전화|연락처|핸드폰|휴대폰){_TELL}",
    # 본인 건강: 질병명 뒤에 보유·진단 표현. "치매가 있는 어르신"처럼 남을 가리키면 통과한다
    rf"(?:{_ILLNESS})\s*(?:이|가|도|은|는)?\s*(?:있(?!으신|는\s*(?:분|어르신|환자))|앓|걸려|걸렸|생겼|판정|때문에)",
    # "당뇨병 환자예요", "치매예요"처럼 본인을 가리키는 끝맺음. "치매 환자 돌봄"은 통과한다
    rf"(?:{_ILLNESS})(?:병)?\s*(?:환자)?\s*(?:이에요|예요|이라서|라서|입니다|이고요)",
    rf"(?:{_ILLNESS})\s*(?:수술|치료|약)\s*(?:을|를|도)?\s*(?:받|먹|하고\s*있|중이)",
    r"진단\s*(?:을|를)?\s*받|병력|투병|지병",
    # 가족사: 가족 호칭 가까이에 생사·혼인·동거·건강 사정
    rf"{_FAMILY}.{{0,12}}?(?:{_FAMILY_EVENT})",
    r"혼자\s*살|가족사",
    # 지시문·역할 전환
    r"(?:이전|기존|지금까지|모든)\s*지시.{0,20}무시",
    r"시스템\s*(?:설정|프롬프트)|개발자\s*(?:메시지|지시)",
    r"이제부터\s*(?:너는|넌|당신은)|(?:너는|넌)\s*이제",
    r"(?:위|앞|처음)(?:에|의)?\s*(?:받은|있는|적힌)?\s*(?:규칙|지시|프롬프트).{0,10}(?:말해|알려|보여|출력|그대로)",
    r"ignore\s+(?:all\s+)?(?:previous|prior)\s+instructions|system\s+prompt",
)
_BLOCKED = re.compile("|".join(_PATTERNS), re.IGNORECASE)


def safe_text(value: str) -> str | None:
    """숨은 문자·과대 입력·알려진 개인정보/지시문은 문장 전체를 제외한다."""
    try:
        normalized = _TEXT.validate_python(value)
    except ValidationError:
        return None
    # 호환 문자로 쓴 숫자·영문 우회를 검사하되 전송 텍스트는 계약의 NFC를 유지한다.
    if _BLOCKED.search(unicodedata.normalize("NFKC", normalized)):
        return None
    return normalized
